import Foundation

/// **「刷新失败」那一句** —— 页面上已经有内容、下拉刷新又失败时的那条轻提示
/// （TECH_SPEC §8.5「刷新不遮挡已有内容」）。
///
/// ## ⚠️ PRD §7 没有这一条，它是 §8.5 推出来的
///
/// PRD §7 的「提示 / 校验」表假定刷新失败时整屏变失败态 —— 那种做法在首屏是对的
/// （屏幕上本来就没东西），而**已有内容时**做同样的事等于把用户正看着的内容擦掉。
/// §8.5 因此要求"刷新失败不遮挡已有内容"，于是失败必须另找一处说出口：一条 toast。
///
/// ## ⚠️ 它为什么在这里（而不是继续散在各 ViewModel 里）
///
/// 收口前，这一句在仓里有**四份**同值副本，各自的名字还不一样：
///
/// | 落点 | 名字 | 当时的位置 |
/// |---|---|---|
/// | `HomeCopy.refreshFailed` | 首页 | `HomeViewModel` |
/// | `ExploreRepoCopy.refreshFailed` | 探索仓库详情 | `ExploreRepoViewModel` |
/// | `CommitDetailViewModel.refreshFailedToast` | 提交详情 | 自身 |
/// | `RepoDetailViewModel.refreshFailedToast` | 仓库详情 | 自身 |
///
/// 四处的注释互相写着"同 XX"，说明大家都知道它是一句话 —— 但改起来要改四处，
/// 而漏掉一处不会报错：只会让某个页面上出现一句措辞不同的话。
///
/// ⚠️ **四处都写在一个文件里、而且都在 App target**：切片 7.4 落地本类型时
/// 数漏了 `RepoDetailViewModel` 那一份（`actionFailedToast` 就在它下面几行），
/// 于是当时记的是"三处"。四处这个数是从 `grep refreshFailed` 的结果里数出来的。
///
/// ## 切片 7.4 做过什么
///
/// 1. **立本类型作正本**——Issue 详情与 PR 详情也要用它（两页都有下拉刷新），
///    不收口就是第六份。
/// 2. **把那四份旧副本删掉**，四个调用点全部改成 `RefreshCopy.failed`。
///
/// 第 2 步不是"顺手"：一个**没有任何调用方**的正本只是第五份副本，
/// 而且比原来更坏 —— 它多了一个"看起来已经收口了"的假象。
///
/// ⚠️ 那四份都在 App target（本包看不见它们）⇒ 这四条删除**没有包测试守得住**，
/// 只能靠 `grep -rn "刷新失败"` 在收口后归零来验证。
public enum RefreshCopy {

    /// 下拉刷新失败、且屏幕上已有内容时的那条提示。
    ///
    /// 后半句 `下拉可重试` 是**操作引导**，不是客套：它告诉用户"重试的入口还在原来
    /// 那个手势上"，否则失败这件事就没有出口（PRD §1 设计原则 4）。
    public static let failed = "刷新失败 · 下拉可重试"
}

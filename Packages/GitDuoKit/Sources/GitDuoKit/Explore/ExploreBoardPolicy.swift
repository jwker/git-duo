import Foundation

/// 探索页的**配额纪律参数**（TECH_SPEC §13.2 第 1–4 条、风险登记表 #16）。
///
/// ## 为什么这些数必须收在一处
///
/// 探索页与搜索页**共用同一个 Search 桶**（30 次/分钟，§9.10.1）。用户在新星 / 活跃
/// × 日期 × 语言之间连点几下，一分钟内就能撞配额 —— 而后果不是"探索页慢一点"，
/// 是**搜索页一起 403**。所以这几个数不是"优化参数"，是**功能约束**：
///
/// - 任意一处调小，页面会无故多发请求；
/// - 任意一处调大，用户会觉得"切了但没反应"。
///
/// 理论最坏值（§13.2 第 3 条）：`2 榜 × 3 日期 × 6 语言 = 36` 种组合 ⇒
/// 光靠防抖压不住，必须叠加"按组合复用缓存"（决策 #37）。
public enum ExploreBoardPolicy {

    /// 切榜 / 切筛选的**防抖时长**：`≥300ms`（§13.2 第 2 条）。
    ///
    /// ⚠️ 它与搜索页的"边输边搜"防抖是**同一个数、但两个用途**：
    /// 那边防的是"每个字符一次请求"，这边防的是"每个连点一次请求"。
    /// 都取 300ms 是巧合而非复用 —— 所以各自留一份常量、各自注明出处，不要合并成一个。
    public static let switchDebounce: Duration = .milliseconds(300)

    /// 榜单组合缓存的内存上限（决策 #37）。
    ///
    /// 全部组合可达 `2 榜 × 4 档日期（含未选）× 6 种语言（含未选）= 48` 种，
    /// 但真实使用是**少数几个组合反复横跳**；LRU 只留"最近用过"的那批，12 足够覆盖实际路径。
    public static let cacheCapacity = 12

    /// 一页多少条。与其余列表一致（§4.4）。
    ///
    /// 转发 `ExploreQueryBuilder.pageSize` 而不是另写一个 30 —— 两份"30"迟早分叉，
    /// 而分叉的表现是"分页步长与 `Link` 头对不上"，极难排查。
    public static var pageSize: Int { ExploreQueryBuilder.pageSize }
}

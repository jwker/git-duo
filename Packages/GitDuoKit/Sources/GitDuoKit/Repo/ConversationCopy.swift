/// **对话**（Issue 评论 / PR 时间线）共用的那一套文案。
///
/// ## 为什么这几句不放在 `IssueCopy` 或 `PullCopy`
///
/// Issue 详情（PRD §4.9）与 PR 详情（§4.11）的评论输入区是**同一件事**：
/// 同一个端点（`POST /issues/{n}/comments`，PR 的评论也走它）、同一句空内容提示、
/// 同一个"评论已发送"。§7「提示 / 校验」也只给了它们**一行**
/// （`先写点内容再发送` / `评论已发送`）。
///
/// 放在两个页面各自那份文案里，就会变成"改一句要改两处"，
/// 而漏掉一处不会报错 —— 只会让两个页面对同一件事说不同的话。
///
/// ⚠️ **两处真正不同的只有输入框占位**（Issue 是 `写评论… (Markdown 支持)`、
/// PR 是 `写评论…`，原型逐字如此），所以那一条**留在各自的页面文案里**。
///
/// ## ⚠️ 发送失败提示条：PR 页也用它（规格未给，此处是**有意复用**）
///
/// PRD §4.9 逐字给了 `⚠ 发送失败：网络不可用。草稿已保留，可重试。`，
/// 而 §4.11 只写了「输入非空时把评论追加到讨论列表；空内容时提示先写内容」，
/// **没有**给失败的呈现。§7「错误态」里那句是通用的（只写了"评论发送失败"）。
///
/// 这里的选择是**两个页面用同一句**：同一次操作（发评论）在两个页面上没有任何区别，
/// 差别只在于 PR 页的原型（`08-pr.js:143`）没画失败那条路。
/// 编一句不一样的提示，等于让用户以为"PR 的评论失败和 Issue 的不一样"。
/// 已登记为有意偏差。
public enum ConversationCopy {

    /// 内容为空时点发送（PRD §7 逐字）。
    public static let emptyCommentToast = "先写点内容再发送"

    /// 发送成功（PRD §7 逐字）。
    public static let commentSentToast = "评论已发送"

    /// 发送按钮的文案（原型 `06-files.js:138` 与 `08-pr.js:59` **逐字相同**，都是 `发送`）。
    ///
    /// ⚠️ 它原先放在 `IssueCopy`（7.1 按"§4.9 的评论输入区"归的类），但 PR 页用的是
    /// **同一个词** —— 与上面那三句同一条理由移到本类型：两页共用的话语只写一遍。
    /// 放在 `IssueCopy` 里的代价不是报错，而是将来给 PR 页换措辞时只改了一处。
    public static let sendAction = "发送"

    /// 发送失败提示条（PRD §4.9 与 §7「错误态」逐字，含 `⚠`）。
    ///
    /// ⚠️ 这句是**一句承诺**：`草稿已保留，可重试`。它成立的唯一前提是草稿真的落了盘
    /// （决策 #59 / `CommentDraftStore`）—— 只留内存的话"返回再进来"就丢了，
    /// 而这句会照说。文案与实现必须同时成立。
    public static let sendFailureNotice = "⚠ 发送失败：网络不可用。草稿已保留，可重试。"
}

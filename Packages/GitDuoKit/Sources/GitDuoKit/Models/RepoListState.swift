import Foundation

/// Issue / PR 列表**取哪一档**（TECH_SPEC §9.8 / §9.9、PRD §4.4 分区二·三、决策 #56 / #61）。
///
/// ## 为什么要有这个类型，而不是让调用方传字符串
///
/// 服务端的 `?state=` 是个**三取值**参数（`open` / `closed` / `all`），而三个调用方的
/// 意图各不相同：
///
/// | 调用方 | 取值 | 之后再滤什么 |
/// |---|---|---|
/// | 探索 Issues 列表（§4.14、决策 #38） | `.open` | 不用（服务端已只给开放） |
/// | 探索 PR 列表（§4.15、决策 #39） | `.all` | 滤掉「关闭但未合并」 |
/// | 仓库详情 Issues 段（§4.4 分区二、决策 #61） | `.open` / `.closed` | 不用 |
/// | 仓库详情 PR 段（§4.4 分区三、决策 #61） | `.open` / `.closed` | 滤掉「关闭但未合并」 |
///
/// 四个调用方、三种意图 ⇒ 传裸字符串的话，"忘了传 / 传错"一律表现为
/// **一个看起来完全正常的列表**（只是里面少了或多了一些条目）。
/// 枚举把这个选择变成编译期必须做出的事。
///
/// ## ⚠️ 与响应的 `state` **不是同一个词汇表**
///
/// 请求可以取 `.all`，而**响应里的 `state` 只有 `open` / `closed`**
/// （GitHub 没有 `all` 这个状态，它只是"别筛"）。
/// 这正是切片 4 把那个方法命名为 `openIssues` 而不是 `issues(state:)` 的理由
/// （当时只有一种用途）；现在有四种，含混的代价大于多一个类型。
///
/// ⚠️ 另外，PR 的**展示**状态是三档（`open` / `merged` / `closed`，见 `PullRequestState`），
/// 那是由 `state` + `merged_at` **算出来**的，与本类型不是一回事：
/// 本类型只回答"向服务端要哪一批"，「已合并」那一档要**.closed** 再本地分。
public enum RepoListState: String, Sendable, Hashable, CaseIterable {

    /// 只要开放中的。
    case open

    /// 只要已关闭的（含已合并的，两者在服务端长得一样）。
    case closed

    /// **不筛**（服务端语义：`open` + `closed` 全给）。
    ///
    /// ⚠️ 名字叫 `all` 是因为服务端就这么叫；它**不是**一个状态，
    /// 所以永远不要拿它与 `PullRequestState` 或 `IssueRow.isOpen` 对比。
    case all
}
